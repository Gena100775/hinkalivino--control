# Database-backed, atomic request budgets survive restarts and multiple processes.
def throttle(ip, username):
 now=int(time.time())
 denied=False
 with engine.begin() as c:
  c.execute(text('DELETE FROM login_limits WHERE expires<=:now'),{'now':now})
  for kind,value,limit in [('ip',ip,20),('account',username.casefold(),40)]:
   key=hashlib.sha256((kind+':'+value).encode()).hexdigest()
   attempts=c.execute(text('INSERT INTO login_limits(key,attempts,expires) VALUES(:k,1,:e) ON CONFLICT(key) DO UPDATE SET attempts=login_limits.attempts+1 RETURNING attempts'),{'k':key,'e':now+900}).scalar_one()
   denied=denied or attempts>limit
 if denied:raise HTTPException(429,'Too many attempts. Try again later.',headers={'Retry-After':'900'})

# Bound memory consumed by concurrent Argon2 verification.
hash_slots=BoundedSemaphore(2)
def verify_password(encoded,password):
 if not hash_slots.acquire(blocking=False):raise HTTPException(429,'Server busy. Try again shortly.',headers={'Retry-After':'5'})
 try:
  try:return ph.verify(encoded,password)
  except (VerifyMismatchError,VerificationError):return False
 finally:hash_slots.release()

