@app.post('/api/orders/{order_id}/advance')
def advance(order_id:int,u=Depends(auth)):
 require(u,{'owner','manager','chef','souschef','buyer'})
 with engine.begin() as c:
  o=one(c,'SELECT * FROM orders WHERE id=:id FOR UPDATE' if not URL.startswith('sqlite') else 'SELECT * FROM orders WHERE id=:id',{'id':order_id})
  if not o:raise HTTPException(404,'Order not found')
  allow(u,o['site']);steps={'draft':'sent','sent':'delivered','delivered':'received'}
  if o['status'] not in steps:raise HTTPException(409,'Order already received')
  if o['status']=='delivered' and u['role']=='buyer':raise HTTPException(403,'Receiving requires restaurant staff')
  if not URL.startswith('sqlite'):c.execute(text('SELECT id FROM sites WHERE id=:s FOR UPDATE'),{'s':o['site']})
  status=steps[o['status']]
  c.execute(text('UPDATE orders SET status=:status WHERE id=:id'),{'status':status,'id':order_id})
  if status=='received':
   c.execute(text('INSERT INTO stock(site,product_id,qty) VALUES(:s,:p,:q) ON CONFLICT(site,product_id) DO UPDATE SET qty=stock.qty+excluded.qty'),{'s':o['site'],'p':o['product_id'],'q':o['qty']})
   c.execute(text('INSERT INTO movements(site,product_id,delta,reason,order_id,actor,created) VALUES(:s,:p,:d,:r,:o,:a,:t)'),{'s':o['site'],'p':o['product_id'],'d':o['qty'],'r':'receipt','o':order_id,'a':u['id'],'t':int(time.time())})
  audit(c,u['id'],'advance_order',{'id':order_id,'status':status});return {'status':status}
@app.post('/api/inventory')
def inventory(body:Inventory,u=Depends(auth)):
 require(u,{'owner','manager','chef','souschef'});allow(u,body.site)
 with engine.begin() as c:
  if not one(c,'SELECT id FROM products WHERE id=:id',{'id':body.product_id}):raise HTTPException(404,'Product not found')
  # Serialize concurrent inventory updates on a per-site lock row (PostgreSQL).
  if not URL.startswith('sqlite'):c.execute(text('SELECT id FROM sites WHERE id=:s FOR UPDATE'),{'s':body.site})
  old=one(c,'SELECT qty FROM stock WHERE site=:s AND product_id=:p',{'s':body.site,'p':body.product_id});before=float(old['qty']) if old else 0
  delta=body.counted-before
  c.execute(text('INSERT INTO stock(site,product_id,qty) VALUES(:s,:p,:q) ON CONFLICT(site,product_id) DO UPDATE SET qty=excluded.qty'),{'s':body.site,'p':body.product_id,'q':body.counted})
  c.execute(text('INSERT INTO movements(site,product_id,delta,reason,actor,created) VALUES(:s,:p,:d,:r,:a,:t)'),{'s':body.site,'p':body.product_id,'d':delta,'r':'inventory','a':u['id'],'t':int(time.time())})
  audit(c,u['id'],'inventory',{'site':body.site,'product_id':body.product_id,'delta':delta});return {'before':before,'after':body.counted,'difference':delta}
