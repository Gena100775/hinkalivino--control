# Single-instance basic throttle. Use Redis-backed throttle before scaling horizontally.
failures=defaultdict(deque)
def throttle(ip):
 now=time.monotonic();q=failures[ip]
 while q and q[0]<now-900:q.popleft()
 if len(q)>=8:raise HTTPException(429,'Too many attempts. Try again later.')
