  token=secrets.token_urlsafe(48)
  c.execute(text('INSERT INTO sessions(token_hash,user_id,expires) VALUES(:h,:u,:e)'),{'h':hashlib.sha256(token.encode()).hexdigest(),'u':u['id'],'e':int(time.time())+8*3600})
  audit(c,u['id'],'login',{})
  return {'token':token,'username':u['username'],'role':u['role'],'site':u['site']}
