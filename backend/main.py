@app.post('/api/login')
def login(body:Login,request:Request):
 ip=request.client.host if request.client else 'unknown';throttle(ip)
 with engine.begin() as c:
  u=one(c,'SELECT * FROM users WHERE username=:u AND active=TRUE',{'u':body.username})
  try:valid=bool(u) and ph.verify(u['passhash'],body.password)
  except (VerifyMismatchError,VerificationError):valid=False
  if not u:
   try: ph.verify(DUMMY_HASH,body.password)
   except (VerifyMismatchError,VerificationError): pass
  if not valid:
   failures[ip].append(time.monotonic());raise HTTPException(401,'Invalid credentials')
  failures.pop(ip,None)
  c.execute(text('DELETE FROM sessions WHERE expires<=:now'),{'now':int(time.time())})
  token=secrets.token_urlsafe(48)
  c.execute(text('INSERT INTO sessions(token_hash,user_id,expires) VALUES(:h,:u,:e)'),{'h':hashlib.sha256(token.encode()).hexdigest(),'u':u['id'],'e':int(time.time())+8*3600})
  audit(c,u['id'],'login',{})
  return {'token':token,'username':u['username'],'role':u['role'],'site':u['site']}
